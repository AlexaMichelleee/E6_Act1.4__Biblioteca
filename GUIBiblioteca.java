    private void btnCrear2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrear2ActionPerformed
                                            
    if (recep != null) {
        JOptionPane.showMessageDialog(this,
                "El recepcionista ya existe, destrúyelo primero.");
        return;
    }

    try {
        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");

        recep = new Recepcionista();

        recep.setCurp(txtCURP2.getText());
        recep.setNombre(txtNombre2.getText());
        recep.setApellido(txtApellido2.getText());
        recep.setIde(txtIde2.getText());

        if (!txtFechaingreso2.getText().trim().isEmpty()) {
            recep.setIngreso(formato.parse(txtFechaingreso2.getText()));
        }

        recep.setImagen(txtImagen2.getText());
        recep.setEstado(txtEstado2.getText());

        recep.setSalario(Double.parseDouble(txtSalario2.getText()));
        recep.setIdunico(Integer.parseInt(txtIdunico2.getText()));
        recep.setPuesto(txtPuesto2.getText());

        recep.setArea(txtarea1.getText());
        recep.setTurno(txtTurno.getText());

        JOptionPane.showMessageDialog(this,
                "Recepcionista creado correctamente.");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "El salario debe ser un número y el ID debe ser un número entero.",
                "Error",
                JOptionPane.ERROR_MESSAGE);

    } catch (ParseException e) {
        JOptionPane.showMessageDialog(this,
                "La fecha debe tener el formato dd/MM/yyyy.",
                "Error",
                JOptionPane.ERROR_MESSAGE);

    } catch (IllegalArgumentException e) {
        JOptionPane.showMessageDialog(this,
                e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnCrear2ActionPerformed

    private void btnBuscar2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscar2ActionPerformed
        if (recep == null) {
        JOptionPane.showMessageDialog(this,
                "El objeto no ha sido creado.");
        return;
    }

    if (recep.getCurp() == null) {
        JOptionPane.showMessageDialog(this,
                "El recepcionista todavía no tiene una CURP registrada.");
        return;
    }

    if (recep.getCurp().equals(txtCURP2.getText())) {

        txtCURP2.setText(recep.getCurp());
        txtNombre2.setText(recep.getNombre());
        txtApellido2.setText(recep.getApellido());
        txtIde2.setText(recep.getIde());
        txtarea1.setText(recep.getArea());
        txtTurno.setText(recep.getTurno());
        txtIdunico2.setText(recep.getIdunico());
        

        if (recep.getIngreso() != null) {
            SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
            txtFechaingreso2.setText(formato.format(recep.getIngreso()));
        }

        JOptionPane.showMessageDialog(this,
                "Recepcionista encontrado.");

    } else {
        JOptionPane.showMessageDialog(this,
                "CURP no encontrada.");
    }
    }//GEN-LAST:event_btnBuscar2ActionPerformed

