    private void btnBuscar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscar1ActionPerformed
                                               
    if (client == null) {
        JOptionPane.showMessageDialog(this,
                "El objeto no ha sido creado.");
        return;
    }

    if (client.getCurp() == null) {
        JOptionPane.showMessageDialog(this,
                "El cliente todavía no tiene una CURP registrada.");
        return;
    }

    if (client.getCurp().equals(txtCURP1.getText())) {

        txtCURP1.setText(client.getCurp());
        txtNombre1.setText(client.getNombre());
        txtApellido1.setText(client.getApellido());
        txtIde1.setText(client.getIde());
        txtcorreo1.setText(client.getCorreo());
        txtTelefono1.setText(client.getTelefono());
        txtTipocliente1.setText(client.getTipoCliente());
        txtImagen1.setText(client.getImagen());
        txtEstado1.setText(client.getEstado());

        if (client.getIngreso() != null) {
            SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
            txtFechaingreso1.setText(formato.format(client.getIngreso()));
        }

        JOptionPane.showMessageDialog(this, "Cliente encontrado.");

    } else {
        JOptionPane.showMessageDialog(this,
                "CURP no encontrada.");
    }

    }//GEN-LAST:event_btnBuscar1ActionPerformed

    private void btnMostrar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrar1ActionPerformed
                                                   
    if (client == null) {
        JOptionPane.showMessageDialog(this,
                "El objeto no ha sido creado.");
        return;
    }

    String fecha = "";

    if (client.getIngreso() != null) {
        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
        fecha = formato.format(client.getIngreso());
    }

    JOptionPane.showMessageDialog(this,
            "CURP: " + client.getCurp()
            + "\nNombre: " + client.getNombre()
            + "\nApellido: " + client.getApellido()
            + "\nIdentificación: " + client.getIde()
            + "\nFecha de ingreso: " + fecha
            + "\nCorreo: " + client.getCorreo()
            + "\nTeléfono: " + client.getTelefono()
            + "\nTipo de cliente: " + client.getTipoCliente()
            + "\nImagen: " + client.getImagen()
            + "\nEstado: " + client.getEstado(),
            "Datos del Cliente",
            JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_btnMostrar1ActionPerformed

